CREATE DATABASE IF NOT EXISTS MERCADO;
USE MERCADO;

DROP TABLE IF EXISTS LISTA_PRODUTO, PRODUTO, CATEGORIA_PRODUTO, SENHA, CLIENTE;

CREATE TABLE CLIENTE (
    ID_cliente INT AUTO_INCREMENT PRIMARY KEY,
    Email VARCHAR(200) NOT NULL UNIQUE,
    nome  VARCHAR(200) NOT NULL
);

CREATE TABLE SENHA (
    ID_cliente INT PRIMARY KEY,
    senha VARCHAR(255) NOT NULL,
    FOREIGN KEY (ID_cliente) REFERENCES CLIENTE(ID_cliente)
);

CREATE TABLE CATEGORIA_PRODUTO (
    ID_categoria INT AUTO_INCREMENT PRIMARY KEY,
    nome VARCHAR(100) NOT NULL
);

CREATE TABLE PRODUTO (
    ID_produto INT AUTO_INCREMENT PRIMARY KEY,
    nome VARCHAR(200) NOT NULL,
    data_validade DATE,
    estoque INT NOT NULL DEFAULT 0,
    preco DECIMAL(10,2) NOT NULL,
    ID_categoria INT,
    FOREIGN KEY (ID_categoria) REFERENCES CATEGORIA_PRODUTO(ID_categoria)
);

CREATE TABLE LISTA_PRODUTO (
    ID_cliente INT,
    ID_prod INT,
    quantidade INT NOT NULL DEFAULT 1,
    PRIMARY KEY (ID_cliente, ID_prod),
    FOREIGN KEY (ID_cliente) REFERENCES CLIENTE(ID_cliente),
    FOREIGN KEY (ID_prod) REFERENCES PRODUTO(ID_produto)
);